// Make sure that you can write a for loop that prints the numbers from
// 0 to 9 in increasing order without needing to look up anything in this
// book. This is the C++ equivlanet of being able to count to ten in a
// foreign language without using a phrase book


#include <iostream>
using namespace std;

int main() {
    for (int i=0; i<10; i++) {
        cout << i << " " << endl;
    }
    cout << "Done!" << endl;
    return 0;
}
